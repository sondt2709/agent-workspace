// Makes the app icons of the desktop and the phone from the one source mark (openspec
// polish-app-icons): shared/ui/icons/aw-mark.svg. Run: pnpm icons:generate. icons.test.ts checks
// that the committed files are the output of this script for the current source.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import sharp from "sharp";

export const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SOURCE = "shared/ui/icons/aw-mark.svg";

/** The parts of the source mark: one outline, drawn gray, and drawn light in the clip path. */
export interface Mark {
  /** The path data of the outline (a rounded square with a square opening, even-odd). */
  outline: string;
  /** The path data of the clip of the light half (the upper-left triangle). */
  clip: string;
  gray: string;
  light: string;
}

/** Reads the mark of the source SVG; refuses a source of another form. */
export function readMark(svg: string): Mark {
  const path = (id: string) => {
    const m = new RegExp(`<path id="${id}" fill="(#[0-9A-Fa-f]{6})"[^>]* d="([^"]+)"`).exec(svg);
    if (!m) throw new Error(`${SOURCE}: no <path id="${id}" fill="#RRGGBB" ... d="...">`);
    return { fill: m[1]!, d: m[2]! };
  };
  const clip = /<clipPath id="upper-left">\s*<path d="([^"]+)"/.exec(svg);
  if (!clip) throw new Error(`${SOURCE}: no <clipPath id="upper-left"> with one path`);
  const gray = path("gray");
  const light = path("light");
  if (gray.d !== light.d) throw new Error(`${SOURCE}: the gray and the light path differ`);
  return { outline: gray.d, clip: clip[1]!, gray: gray.fill, light: light.fill };
}

/** The mark as SVG elements at (x, y) with the side `size` (the source is 24 × 24). */
function markSvg(
  mark: Mark,
  at: { x: number; y: number; size: number },
  colors: { gray: string; light: string; grayOpacity?: number },
): string {
  const scale = at.size / 24;
  return [
    `<defs><clipPath id="upper-left"><path d="${mark.clip}"/></clipPath></defs>`,
    `<g transform="translate(${at.x} ${at.y}) scale(${scale})">`,
    `<path fill="${colors.gray}" fill-opacity="${colors.grayOpacity ?? 1}" fill-rule="evenodd" d="${mark.outline}"/>`,
    `<path fill="${colors.light}" fill-rule="evenodd" clip-path="url(#upper-left)" d="${mark.outline}"/>`,
    `</g>`,
  ].join("");
}

/** A PNG of an SVG text at its own pixel size. */
async function png(svg: string): Promise<Buffer> {
  return sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toBuffer();
}

/**
 * The macOS app icon: 1024 px, the macOS icon grid (an 824 px tile with a 185 px radius at 100 px),
 * a dark tile (between `raised` and `overlay`) with a soft shadow and a thin light line, the mark
 * at 440 px in the center.
 */
export function macIconSvg(mark: Mark): string {
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">`,
    `<defs><filter id="shadow" x="-10%" y="-10%" width="120%" height="130%">`,
    `<feDropShadow dx="0" dy="12" stdDeviation="14" flood-color="#000000" flood-opacity="0.35"/></filter></defs>`,
    `<rect x="100" y="100" width="824" height="824" rx="185" fill="#18191C" filter="url(#shadow)"/>`,
    `<rect x="101" y="101" width="822" height="822" rx="184" fill="none" stroke="#FFFFFF" stroke-opacity="0.1" stroke-width="2"/>`,
    markSvg(mark, { x: 292, y: 292, size: 440 }, { gray: mark.gray, light: mark.light }),
    `</svg>`,
  ].join("");
}

/** The menu bar template image: 32 px (16 pt at scale 2), black with alpha; the gray half at 50 %. */
export function traySvg(mark: Mark): string {
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="32" height="32" viewBox="0 0 32 32">`,
    markSvg(
      mark,
      { x: 3, y: 3, size: 26 },
      { gray: "#000000", light: "#000000", grayOpacity: 0.5 },
    ),
    `</svg>`,
  ].join("");
}

/** An Android vector drawable of the mark in the 108 dp adaptive canvas (46 dp, centered). */
export function androidLayer(mark: Mark, monochrome: boolean): string {
  const gray = monochrome ? "#80FFFFFF" : `#FF${mark.gray.slice(1).toUpperCase()}`;
  const light = monochrome ? "#FFFFFFFF" : `#FF${mark.light.slice(1).toUpperCase()}`;
  const what = monochrome
    ? "the monochrome layer of the launcher icon (themed icons): the gray half at 50 % alpha"
    : "the foreground layer of the launcher icon";
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/icons.ts from ${SOURCE}: do not edit. The AW mark, ${what}. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <group
        android:translateX="31"
        android:translateY="31"
        android:scaleX="1.9166667"
        android:scaleY="1.9166667">
        <path
            android:fillColor="${gray}"
            android:fillType="evenOdd"
            android:pathData="${mark.outline}" />
        <group>
            <clip-path android:pathData="${mark.clip}" />
            <path
                android:fillColor="${light}"
                android:fillType="evenOdd"
                android:pathData="${mark.outline}" />
        </group>
    </group>
</vector>
`;
}

/** The background color of the launcher icon: the dark `surface` token. */
export const ANDROID_COLORS = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/icons.ts: do not edit. The background layer of the launcher icon. -->
<resources>
    <color name="launcher_background">#0F1011</color>
</resources>
`;

/** The TypeScript module with the menu bar image as base64 PNG. */
export function trayModule(base64: string): string {
  return `// Generated by scripts/icons.ts from ${SOURCE}: do not edit.
// The menu bar icon: a 32 × 32 px template image (black with alpha, shown at scale factor 2) of the
// AW mark. macOS colors a template image for the menu bar.
export const TRAY_ICON_PNG_BASE64 =
  "${base64}";
`;
}

/** One generated file: a text, or a PNG (compared by its pixels). */
export type Output =
  | { path: string; kind: "text"; text: string }
  | { path: string; kind: "png"; png: Buffer }
  | { path: string; kind: "tray"; png: Buffer; text: string };

export const MAC_ICON = "desktop/resources/icon.png";
export const TRAY_MODULE = "desktop/src/main/tray-icon.ts";
const RES = "android/app/src/main/res";

/** Each output of the source mark. */
export async function outputs(svg = readFileSync(join(root, SOURCE), "utf8")): Promise<Output[]> {
  const mark = readMark(svg);
  const tray = await png(traySvg(mark));
  return [
    { path: MAC_ICON, kind: "png", png: await png(macIconSvg(mark)) },
    { path: TRAY_MODULE, kind: "tray", png: tray, text: trayModule(tray.toString("base64")) },
    {
      path: `${RES}/drawable/ic_launcher_foreground.xml`,
      kind: "text",
      text: androidLayer(mark, false),
    },
    {
      path: `${RES}/drawable/ic_launcher_monochrome.xml`,
      kind: "text",
      text: androidLayer(mark, true),
    },
    { path: `${RES}/values/colors.xml`, kind: "text", text: ANDROID_COLORS },
  ];
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const out of await outputs()) {
    writeFileSync(join(root, out.path), out.kind === "png" ? out.png : out.text);
    console.log(`wrote ${out.path}`);
  }
}
