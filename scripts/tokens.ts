// Writes the phone tokens from the desktop tokens (openspec phone-desktop-parity): the colors of
// tokens.dark and tokens.light and the radii of @aw/ui/tokens become AwTokens.kt of the Android app.
// Run: pnpm tokens:generate. tokens.test.ts checks that the committed file is the output of this script.
import { radius, tokens, type SchemeTokens } from "@aw/ui/tokens";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUT = "android/app/src/main/kotlin/com/agentworkspace/android/ui/AwTokens.kt";

/** The tokens that are not a color: the phone has no CSS shadow. */
const NOT_COLORS = new Set<keyof SchemeTokens>(["shadow"]);

/** The Compose ARGB literal of `#RRGGBB` or `rgba(r,g,b,a)`, for example `0xFF08090A`. */
export function argb(value: string): string {
  const hex = /^#([0-9A-Fa-f]{6})$/.exec(value);
  if (hex) return `0xFF${hex[1]!.toUpperCase()}`;
  const rgba = /^rgba\((\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\)$/.exec(value);
  if (!rgba) throw new Error(`a token color must be #RRGGBB or rgba(r,g,b,a), not ${value}`);
  const [r, g, b] = [rgba[1], rgba[2], rgba[3]].map(Number) as [number, number, number];
  const a = Math.round(Number(rgba[4]) * 255);
  const two = (n: number) => n.toString(16).toUpperCase().padStart(2, "0");
  return `0x${two(a)}${two(r)}${two(g)}${two(b)}`;
}

function scheme(name: string, doc: string, values: SchemeTokens): string {
  const lines = (Object.keys(values) as (keyof SchemeTokens)[])
    .filter((key) => !NOT_COLORS.has(key))
    .map((key) => `    val ${key} = Color(${argb(values[key])})`);
  return [`/** ${doc} */`, `internal object ${name} {`, ...lines, "}"].join("\n");
}

/** The text of AwTokens.kt. */
export function kotlin(): string {
  const radii = (Object.keys(radius) as (keyof typeof radius)[]).map(
    (key) => `    val ${key} = ${radius[key]}.dp`,
  );
  return [
    "// Generated by scripts/tokens.ts from shared/ui/src/tokens.ts. Do not edit: run pnpm tokens:generate.",
    "package com.agentworkspace.android.ui",
    "",
    "import androidx.compose.ui.graphics.Color",
    "import androidx.compose.ui.unit.dp",
    "",
    scheme(
      "DarkTokens",
      "The colors of the dark scheme (`tokens.dark` of `@aw/ui/tokens`).",
      tokens.dark,
    ),
    "",
    scheme(
      "LightTokens",
      "The colors of the light scheme (`tokens.light` of `@aw/ui/tokens`).",
      tokens.light,
    ),
    "",
    "/** The radii (`radius` of `@aw/ui/tokens`, docs/design.md 5). */",
    "internal object AwRadius {",
    ...radii,
    "}",
    "",
  ].join("\n");
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  writeFileSync(join(root, OUTPUT), kotlin());
  console.log(`wrote ${OUTPUT}`);
}
