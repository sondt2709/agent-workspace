// The Kotlin target of `pnpm schema:generate` (docs/phase-1.md 3.4): Kotlin data classes for
// kotlinx.serialization, rendered from the generated JSON Schemas. The Android module
// android/shared compiles them in commonMain (source folder android/shared/generated/kotlin). The classes call `AwChecks` of that module.
//
// Rules of the mapping (openspec change add-android-shared-model, design decisions 1 to 4):
// - An object with properties is a `@Serializable data class`. A decode ignores unknown keys; the
//   reader keeps them from the raw JSON (a zod `looseObject`).
// - A field with a default gets the same default. A field that is not required and has no default
//   is nullable with the default null. When its schema does not allow null (a zod `.optional()`),
//   it has `@AwOptional` (the reader refuses a JSON null, like zod) and
//   `@EncodeDefault(EncodeDefault.Mode.NEVER)` (a writer leaves out the key, it never writes null).
// - `anyOf [X, null]` and `type: [X, "null"]` are nullable. An enum is a `String` with a check.
// - `integer` is `Long`, `number` is `Double`, a `number` const is `Int`.
// - An object with `propertyNames` or a typed `additionalProperties` is a `Map<String, V>`. An
//   object with no properties and an empty `additionalProperties` is a `JsonObject`.
// - The `init` block checks each const, enum, pattern, length, range and `x-aw-check`, so a decode
//   is also the validation.
import { z } from "zod";
import { AW_CHECK } from "../src/common.ts";
import { eventEnvelope } from "../src/events.ts";
import type { SchemaEntry } from "../src/registry.ts";

type Schema = Record<string, unknown>;

export const KOTLIN_PACKAGE = "com.agentworkspace.schema";
export const KOTLIN_DIR = "android/shared/generated/kotlin";
const PACKAGE_DIR = `${KOTLIN_DIR}/${KOTLIN_PACKAGE.split(".").join("/")}`;

const NOTE = "Generated by `pnpm schema:generate` from shared/schema/src. Do not edit.";

const KEYWORDS = new Set([
  "as",
  "break",
  "class",
  "continue",
  "do",
  "else",
  "false",
  "for",
  "fun",
  "if",
  "in",
  "interface",
  "is",
  "null",
  "object",
  "package",
  "return",
  "super",
  "this",
  "throw",
  "true",
  "try",
  "typealias",
  "typeof",
  "val",
  "var",
  "when",
  "while",
]);

/** `first_message` → `firstMessage`. */
function camel(name: string): string {
  const text = name.replace(/[-_.]+([a-z0-9])/g, (_, c: string) => c.toUpperCase());
  return KEYWORDS.has(text) ? `\`${text}\`` : text;
}

/** `test-servers` or `task.created` → `TestServers`, `TaskCreated`. */
export function pascal(name: string): string {
  return name
    .split(/[-_.]+/)
    .filter((part) => part !== "")
    .map((part) => part[0]!.toUpperCase() + part.slice(1))
    .join("");
}

/** A Kotlin string literal. */
function str(text: string): string {
  return `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$").replace(/\n/g, "\\n")}"`;
}

/**
 * A JavaScript pattern (no flags) as a Java pattern. A Java `$` also matches before a last line
 * break, so each `$` anchor outside a character class becomes `\\z` (the end of the input).
 */
export function javaPattern(pattern: string): string {
  let out = "";
  let inClass = false;
  for (let i = 0; i < pattern.length; i++) {
    const c = pattern[i]!;
    if (c === "\\") {
      out += c + (pattern[i + 1] ?? "");
      i++;
    } else if (c === "[") {
      inClass = true;
      out += c;
    } else if (c === "]") {
      inClass = false;
      out += c;
    } else if (c === "$" && !inClass) out += "\\z";
    else out += c;
  }
  return out;
}

/** The constants of one file: each regex and each set of enum values once. */
class Constants {
  readonly #items = new Map<string, string>();

  #add(prefix: string, code: string): string {
    const found = this.#items.get(code);
    if (found) return found;
    const name = `${prefix}_${this.#items.size}`;
    this.#items.set(code, name);
    return name;
  }

  regex(pattern: string): string {
    return this.#add("PATTERN", `Regex(${str(javaPattern(pattern))})`);
  }

  values(values: readonly string[]): string {
    return this.#add("VALUES", `setOf(${values.map(str).join(", ")})`);
  }

  render(): string[] {
    return [...this.#items].map(([code, name]) => `private val ${name} = ${code}`);
  }
}

interface Shape {
  /** The Kotlin type without the `?`. */
  type: string;
  nullable: boolean;
  /** The schema of the value, without the null branch. */
  schema: Schema;
}

function isNull(schema: unknown): boolean {
  return (schema as Schema | undefined)?.type === "null";
}

/** Removes the null branch of a nullable schema. */
function unwrap(schema: Schema): { schema: Schema; nullable: boolean } {
  const anyOf = schema.anyOf as Schema[] | undefined;
  if (anyOf && anyOf.length === 2 && anyOf.some(isNull)) {
    return { schema: anyOf.find((s) => !isNull(s))!, nullable: true };
  }
  if (Array.isArray(schema.type) && schema.type.length === 2 && schema.type.includes("null")) {
    const { type, ...rest } = schema;
    return {
      schema: { ...rest, type: (type as string[]).find((t) => t !== "null") },
      nullable: true,
    };
  }
  if (anyOf) throw new Error(`Unsupported anyOf: ${JSON.stringify(schema)}`);
  return { schema, nullable: false };
}

function isMap(schema: Schema): boolean {
  if (schema.type !== "object" || schema.properties !== undefined) return false;
  const extra = schema.additionalProperties as Schema | undefined;
  return (
    schema.propertyNames !== undefined || (extra !== undefined && Object.keys(extra).length > 0)
  );
}

class ClassWriter {
  readonly constants = new Constants();

  /** The Kotlin type of a schema. `nested` is the class name for an object with properties. */
  shape(raw: Schema, nested: string): Shape {
    const { schema, nullable } = unwrap(raw);
    const type = schema.type;
    let kotlin: string;
    if (type === "string") kotlin = "String";
    else if (type === "boolean") kotlin = "Boolean";
    else if (type === "integer") kotlin = "Long";
    else if (type === "number") kotlin = schema.const === undefined ? "Double" : "Int";
    else if (type === "array") {
      kotlin = `List<${this.full(this.shape(schema.items as Schema, `${nested}Item`))}>`;
    } else if (type === "object") {
      if (schema.properties !== undefined) kotlin = nested;
      else if (isMap(schema)) {
        const value = (schema.additionalProperties as Schema | undefined) ?? {};
        const shape =
          Object.keys(value).length > 0
            ? this.full(this.shape(value, `${nested}Value`))
            : "JsonElement";
        kotlin = `Map<String, ${shape}>`;
      } else kotlin = "JsonObject";
    } else throw new Error(`Unsupported schema: ${JSON.stringify(schema)}`);
    return { type: kotlin, nullable, schema };
  }

  full(shape: Shape): string {
    return shape.nullable ? `${shape.type}?` : shape.type;
  }

  /**
   * The check statements of one value. `expr` is a non-null Kotlin expression, and `l` is the
   * Kotlin expression of the field path in the message (for example `"credentials" + "." + index`).
   */
  checks(schema: Schema, expr: string, l: string, nested: string): string[] {
    const out: string[] = [];
    if (schema.const !== undefined) {
      out.push(`AwChecks.equal(${expr}, ${this.literal(schema.const, schema, nested)}, ${l})`);
    }
    if (Array.isArray(schema.enum)) {
      out.push(`AwChecks.oneOf(${expr}, ${this.constants.values(schema.enum as string[])}, ${l})`);
    }
    if (typeof schema.pattern === "string") {
      out.push(`AwChecks.pattern(${expr}, ${this.constants.regex(schema.pattern)}, ${l})`);
    }
    if (typeof schema.minLength === "number")
      out.push(`AwChecks.minLength(${expr}, ${schema.minLength}, ${l})`);
    if (typeof schema.maxLength === "number")
      out.push(`AwChecks.maxLength(${expr}, ${schema.maxLength}, ${l})`);
    if (typeof schema.minItems === "number" && schema.minItems > 0)
      out.push(`AwChecks.minItems(${expr}, ${schema.minItems}, ${l})`);
    if (typeof schema.maxItems === "number")
      out.push(`AwChecks.maxItems(${expr}, ${schema.maxItems}, ${l})`);
    const suffix = schema.type === "integer" ? "L" : schema.type === "number" ? ".0" : "";
    if (typeof schema.minimum === "number")
      out.push(`AwChecks.atLeast(${expr}, ${schema.minimum}${suffix}, ${l})`);
    if (typeof schema.maximum === "number")
      out.push(`AwChecks.atMost(${expr}, ${schema.maximum}${suffix}, ${l})`);
    const check = schema[AW_CHECK];
    if (check === "hlc") out.push(`AwChecks.hlc(${expr}, ${l})`);
    else if (check === "relative-path") out.push(`AwChecks.relativePath(${expr}, ${l})`);
    else if (check !== undefined) throw new Error(`Unknown ${AW_CHECK}: ${JSON.stringify(check)}`);
    if (schema.type === "array") {
      const item = unwrap(schema.items as Schema);
      const inner = this.checks(item.schema, "item", `${l} + "." + index`, `${nested}Item`);
      if (inner.length > 0) {
        out.push(`${expr}.forEachIndexed { index, item ->`);
        out.push(...this.guard(item.nullable, "item", inner).map((s) => `    ${s}`));
        out.push("}");
      }
    }
    if (schema.type === "object" && isMap(schema)) {
      const keys = this.checks(
        (schema.propertyNames as Schema | undefined) ?? {},
        "key",
        `${l} + "." + key`,
        nested,
      );
      const extra = (schema.additionalProperties as Schema | undefined) ?? {};
      const value = Object.keys(extra).length > 0 ? unwrap(extra) : null;
      const values = value
        ? this.checks(value.schema, "value", `${l} + "." + key`, `${nested}Value`)
        : [];
      if (keys.length + values.length > 0) {
        out.push(`${expr}.forEach { (key, value) ->`);
        out.push(...keys.map((s) => `    ${s}`));
        if (value) out.push(...this.guard(value.nullable, "value", values).map((s) => `    ${s}`));
        out.push("}");
      }
    }
    return out;
  }

  guard(nullable: boolean, expr: string, statements: string[]): string[] {
    if (!nullable || statements.length === 0) return statements;
    return [`if (${expr} != null) {`, ...statements.map((s) => `    ${s}`), "}"];
  }

  /** A Kotlin literal of a JSON value (a default or a const) of a schema. */
  literal(value: unknown, raw: Schema, nested: string): string {
    if (value === null) return "null";
    const { schema } = unwrap(raw);
    if (typeof value === "string") return str(value);
    if (typeof value === "boolean") return String(value);
    if (typeof value === "number") {
      if (schema.type === "integer") return `${value}L`;
      if (schema.type === "number" && schema.const === undefined) return `${value}.0`;
      return String(value);
    }
    if (Array.isArray(value)) {
      if (value.length === 0) return "emptyList()";
      const items = schema.items as Schema;
      return `listOf(${value.map((v) => this.literal(v, items, `${nested}Item`)).join(", ")})`;
    }
    if (typeof value === "object") {
      if (schema.properties === undefined) {
        if (Object.keys(value).length === 0)
          return isMap(schema) ? "emptyMap()" : "JsonObject(emptyMap())";
        throw new Error(`Unsupported default: ${JSON.stringify(value)}`);
      }
      const props = schema.properties as Record<string, Schema>;
      const args = Object.entries(value as Record<string, unknown>).map(
        ([key, v]) => `${camel(key)} = ${this.literal(v, props[key]!, `${nested}${pascal(key)}`)}`,
      );
      return `${nested}(${args.join(", ")})`;
    }
    throw new Error(`Unsupported literal: ${JSON.stringify(value)}`);
  }

  /** The lines of one data class and its nested classes. */
  dataClass(
    name: string,
    schema: Schema,
    options: { implements?: string; doc?: string } = {},
  ): string[] {
    const props = (schema.properties ?? {}) as Record<string, Schema>;
    const required = new Set((schema.required ?? []) as string[]);
    const params: string[] = [];
    const checks: string[] = [];
    const nested: string[][] = [];
    for (const [key, raw] of Object.entries(props)) {
      const className = pascal(key);
      const shape = this.shape(raw, className);
      const hasDefault = Object.hasOwn(raw, "default");
      const optional = !required.has(key) && !hasDefault;
      const type = optional ? `${shape.type}?` : this.full(shape);
      const init = hasDefault
        ? ` = ${this.literal(raw.default, raw, className)}`
        : optional
          ? " = null"
          : "";
      // A zod `.optional()`: the key may be absent, but null breaks the type.
      const absentOnly = optional && !shape.nullable ? `${ABSENT_ONLY} ` : "";
      params.push(`${absentOnly}@SerialName(${str(key)}) val ${camel(key)}: ${type}${init},`);
      const statements = this.checks(shape.schema, camel(key), str(key), className);
      checks.push(...this.guard(shape.nullable || optional, camel(key), statements));
      nested.push(...this.nestedClasses(shape.schema, className));
    }
    const head = options.implements ? `) : ${options.implements} {` : ") {";
    const lines: string[] = [];
    if (options.doc) lines.push(`/** ${options.doc} */`);
    if (params.length === 0) {
      // A data class needs a parameter: an event with no data fields is a class with no state.
      const parent = options.implements ? ` : ${options.implements}` : "";
      lines.push("@Serializable", `class ${name}${parent} {`);
      lines.push(`    override fun equals(other: Any?): Boolean = other is ${name}`, "");
      lines.push(`    override fun hashCode(): Int = ${str(name)}.hashCode()`, "}");
      return lines;
    }
    const empty = checks.length === 0 && nested.length === 0;
    const close = options.implements ? `) : ${options.implements}` : ")";
    lines.push("@Serializable", `data class ${name}(`, ...params.map((p) => `    ${p}`));
    if (empty) {
      lines.push(close);
      return lines;
    }
    lines.push(head);
    if (checks.length > 0) {
      lines.push("    init {", ...checks.map((c) => `        ${c}`), "    }");
    }
    for (const block of nested)
      lines.push("", ...block.map((line) => (line === "" ? "" : `    ${line}`)));
    lines.push("}");
    return lines;
  }

  /** The nested classes of the objects inside a value. */
  nestedClasses(schema: Schema, name: string): string[][] {
    if (schema.type === "object" && schema.properties !== undefined)
      return [this.dataClass(name, schema)];
    if (schema.type === "array")
      return this.nestedClasses(unwrap(schema.items as Schema).schema, `${name}Item`);
    if (schema.type === "object" && isMap(schema)) {
      const extra = (schema.additionalProperties as Schema | undefined) ?? {};
      if (Object.keys(extra).length > 0)
        return this.nestedClasses(unwrap(extra).schema, `${name}Value`);
    }
    return [];
  }
}

/** The annotations of a field that may be absent but not null (`@AwOptional` is in AwChecks.kt). */
const ABSENT_ONLY = "@AwOptional @EncodeDefault(EncodeDefault.Mode.NEVER)";

function file(imports: string[], body: string[], constants: Constants): string {
  const optIn = imports.includes("kotlinx.serialization.EncodeDefault")
    ? ["@file:OptIn(ExperimentalSerializationApi::class)", ""]
    : [];
  const lines = [
    `// ${NOTE}`,
    "",
    ...optIn,
    `package ${KOTLIN_PACKAGE}`,
    "",
    ...imports.sort().map((i) => `import ${i}`),
    "",
  ];
  const consts = constants.render();
  if (consts.length > 0) lines.push(...consts, "");
  lines.push(...body);
  return `${lines.join("\n")}\n`;
}

const BASE_IMPORTS = ["kotlinx.serialization.SerialName", "kotlinx.serialization.Serializable"];

function importsOf(text: string): string[] {
  const imports = [...BASE_IMPORTS];
  if (/\bJsonObject\b/.test(text)) imports.push("kotlinx.serialization.json.JsonObject");
  if (/\bJsonElement\b/.test(text)) imports.push("kotlinx.serialization.json.JsonElement");
  if (/\bKSerializer\b/.test(text)) imports.push("kotlinx.serialization.KSerializer");
  if (text.includes("@EncodeDefault")) {
    imports.push(
      "kotlinx.serialization.EncodeDefault",
      "kotlinx.serialization.ExperimentalSerializationApi",
    );
  }
  return imports;
}

function jsonSchemaOf(schema: z.ZodType): Schema {
  return z.toJSONSchema(schema, { target: "draft-2020-12", io: "input" });
}

/** `task.v1` → `TaskV1`. */
export function className(entry: string): string {
  const [type, major] = entry.split(/\.v(?=\d+$)/);
  return `${pascal(type!)}V${major}`;
}

/** One document or event schema as one Kotlin file. */
function renderObject(name: string, title: string, schema: Schema): string {
  const writer = new ClassWriter();
  const body = writer.dataClass(name, schema, { doc: `${title}.` });
  const text = body.join("\n");
  return file(importsOf(text), body, writer.constants);
}

/** The event union: one data class per event type, the sealed interface and the registry. */
function renderEvents(name: string, title: string, schema: Schema): string {
  const writer = new ClassWriter();
  const variants = (schema.oneOf ?? schema.anyOf) as Schema[];
  const major = name.slice(name.lastIndexOf("V") + 1);
  const sealed = `EventDataV${major}`;
  const body: string[] = [
    `/** The data of an event of a known type: ${title}. */`,
    `sealed interface ${sealed}`,
    "",
  ];
  const registry: string[] = [];
  for (const variant of variants) {
    const props = variant.properties as Record<string, Schema>;
    const type = props.type!.const as string;
    const dataName = `${pascal(type)}V${major}`;
    body.push(
      ...writer.dataClass(dataName, props.data!, {
        implements: sealed,
        doc: `The data of \`${type}\`.`,
      }),
      "",
    );
    registry.push(`${str(type)} to ${dataName}.serializer(),`);
  }
  body.push(
    `/** The data serializer of each event type, version ${major}. */`,
    `object EventTypesV${major} {`,
    `    val serializers: Map<String, KSerializer<out ${sealed}>> = mapOf(`,
    ...registry.map((r) => `        ${r}`),
    "    )",
    "}",
  );
  const text = body.join("\n");
  return file(importsOf(text), body, writer.constants);
}

export interface KotlinFile {
  path: string;
  content: string;
}

/** Renders the Kotlin files of the schema entries, and the event envelope. */
export function renderKotlin(entries: readonly SchemaEntry[]): KotlinFile[] {
  const out: KotlinFile[] = [];
  for (const entry of entries) {
    const name = className(entry.name);
    const schema = jsonSchemaOf(entry.schema);
    const content = schema.oneOf
      ? renderEvents(`EventV${entry.name.split(".v")[1]}`, entry.title, schema)
      : renderObject(name, entry.title, schema);
    out.push({
      path: `${PACKAGE_DIR}/${schema.oneOf ? `EventTypesV${entry.name.split(".v")[1]}` : name}.kt`,
      content,
    });
  }
  // The envelope of any event, also of an unknown type (docs/phase-1.md 3.4.4).
  out.push({
    path: `${PACKAGE_DIR}/EventEnvelopeV1.kt`,
    content: renderObject(
      "EventEnvelopeV1",
      "The envelope of an event of any type",
      jsonSchemaOf(eventEnvelope),
    ),
  });
  return out;
}
